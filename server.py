def migrate(db):
    """Create or upgrade the schema: CREATE ... IF NOT EXISTS plus the add-only MIGRATIONS.
    Runs under a lock, so several instances starting at once on one database are safe."""
    if not db.pg:
        db.execute("PRAGMA journal_mode=WAL")  # persistent; can't run inside a transaction
    db.lock(MIGRATION_LOCK)
    db.script(SCHEMA.format(**DIALECTS[db.dialect]))
    for table, column, definition in MIGRATIONS:
        if column not in db.columns(table):
            db.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")
            logging.info("Migrated database: added %s.%s", table, column)
    db.script(POST_MIGRATION)
    db.commit()


def bootstrap_admin(db, username, password, dev_mode):
    # Locked, so two instances starting on an empty database create only one admin.
    db.lock(MIGRATION_LOCK)
    if db.execute("SELECT 1 FROM users LIMIT 1").fetchone():
        db.commit()
        if password:
            logging.info("ADMIN_PASSWORD is ignored because user accounts already exist.")
        return
    username = (username or "admin").strip().lower()
    if not USERNAME_RE.fullmatch(username):
        raise SystemExit("ADMIN_USERNAME must be 2–32 characters: letters, digits, dot, dash, underscore.")
    if not password:
        if not dev_mode:
            raise SystemExit("Set ADMIN_PASSWORD to create the first admin account, or DEV_MODE=1 for local development.")
        password = secrets.token_urlsafe(12)
        logging.warning("DEV_MODE: created admin %r with generated password: %s", username, password)
    problem = password_problem(password, username)
    if problem:
        raise SystemExit("ADMIN_PASSWORD: " + problem)
    timestamp = now()
    db.execute("INSERT INTO users(username,display_name,role,password_hash,must_change,created,updated) VALUES(?,?,'admin',?,0,?,?)",
               (username, username, hash_password(password), timestamp, timestamp))
    db.commit()
    logging.warning("Created the first admin account %r.", username)


def create_server(host="0.0.0.0", port=3000, data_dir="data", admin_username="admin", admin_password="",
                  dev_mode=False, trust_proxy=False, database_url=None):
    database = Database(database_url, data_dir)
    if database.name == "sqlite":
        Path(data_dir).mkdir(parents=True, exist_ok=True)
    try:
        with closing(database.connect(timeout=30)) as db:
            migrate(db)
            bootstrap_admin(db, admin_username, admin_password, dev_mode)
    except database.unavailable as exc:
        raise SystemExit(f"Can't use the {database.name} database at {database.where}: {exc}") from None
    logging.info("Storage: %s at %s", database.name, database.where)
    server = ThreadingHTTPServer((host, port), Handler)
    server.database = database
    server.trust_proxy = trust_proxy
    # Login throttling is per process. With several instances behind a VIP, each keeps its own counters.
    server.user_throttle = Throttle(limit=5)
    server.ip_throttle = Throttle(limit=20)
    return server


class AdminError(Exception):
    pass


def import_sqlite(database, source, force):
    """Copy every row of a dark-triage SQLite file into an empty PostgreSQL database, keeping ids."""
    if database.name != "postgres":
        raise AdminError("import-sqlite copies into PostgreSQL: set DATABASE_URL to the target database.")
    source = Path(source)
    if not source.is_file():
        raise AdminError(f"no SQLite database at {source}.")
    # Snapshot the file into memory (consistent even while a server writes to it), then bring the
    # copy up to the current schema. The file itself is only read.
    with closing(sqlite3.connect(source.resolve().as_uri() + "?mode=ro", uri=True)) as original:
        copy = sqlite3.connect(":memory:")
        original.backup(copy)
    copy.row_factory = sqlite3.Row
    with closing(Connection(copy, Database())) as old, closing(database.connect(timeout=15)) as db:
        migrate(old)
        migrate(db)
        with db:
            db.lock(MIGRATION_LOCK)  # keeps starting instances from bootstrapping an admin meanwhile
            existing = {t: db.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in ("users", "tickets")}
            if any(existing.values()):
                if not force:
                    raise AdminError(f"the target database already has {existing['users']} users and {existing['tickets']} "
                                     "tickets. Use --force to DELETE everything in it and import anyway.")
                db.execute("TRUNCATE comments, tickets, sessions, api_tokens, users")
            counts = {}
            for table in TABLES:
                columns = [c for c in (row[1] for row in old.execute(f"PRAGMA table_info({table})")) if c in db.columns(table)]
                rows = [tuple(row) for row in old.execute(f"SELECT {','.join(columns)} FROM {table}")]
                if rows:
                    sql = f"INSERT INTO {table}({','.join(columns)}) VALUES({','.join('%s' for _ in columns)})"
                    db.raw.cursor().executemany(sql, rows)
                counts[table] = len(rows)
                if table != "sessions":
                    # Identity columns don't advance on explicit ids: continue after the highest one.
                    db.execute(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                               f"COALESCE((SELECT MAX(id) FROM {table}), 0) + 1, false)")
    return counts


def admin_cli(argv):
    """Host-side account management: `python server.py admin <command>`. Safe while the server runs
    (SQLite WAL, or PostgreSQL). Uses DATABASE_URL when it is set, like the server."""
    import argparse
    parser = argparse.ArgumentParser(prog="python server.py admin",
                                     description="Manage dark-triage accounts and API tokens without the web UI. "
                                                 "Uses PostgreSQL when DATABASE_URL is set, else SQLite in --data-dir.")
    parser.add_argument("--data-dir", default=os.environ.get("DATA_DIR", "data"),
                        help="directory holding triage.db (default: $DATA_DIR or ./data)")
    commands = parser.add_subparsers(dest="command", required=True, metavar="COMMAND")
    create = commands.add_parser("create-user", help="create an account (no-op if the username exists)")
    create.add_argument("--username", required=True)
    create.add_argument("--display-name", help="defaults to the username")
    create.add_argument("--role", choices=ROLES, default="user")
    create.add_argument("--bot", action="store_true", help="API-token-only account, e.g. for an AI agent")
    create.add_argument("--color", help="avatar color as #rrggbb")
    mint = commands.add_parser("create-token", help="create an API token and print it (only) on stdout")
    mint.add_argument("--username", required=True)
    mint.add_argument("--name", required=True, help="label, e.g. the host or agent using it")
    commands.add_parser("list-users", help="list accounts and their active tokens")
    revoke = commands.add_parser("revoke-token", help="revoke a user's active token by name")
    revoke.add_argument("--username", required=True)
    revoke.add_argument("--name", required=True)
    importer = commands.add_parser("import-sqlite", help="copy a SQLite database into the empty PostgreSQL database at DATABASE_URL")
    importer.add_argument("--from", dest="source", required=True, metavar="PATH", help="the SQLite file, e.g. /app/data/triage.db")
    importer.add_argument("--force", action="store_true", help="import even if the target has data: DELETES all of it first")
    args = parser.parse_args(argv)
    fail = lambda message: (print(f"error: {message}", file=sys.stderr), 1)[1]

    database = Database(os.environ.get("DATABASE_URL"), args.data_dir)
    try:
        if args.command == "import-sqlite":
            try:
                counts = import_sqlite(database, args.source, args.force)
            except AdminError as exc:
                return fail(exc)
            print(f"Imported {args.source} into {database.where}: " + ", ".join(f"{t} {n}" for t, n in counts.items()))
            return 0
        if not database.exists():
            if args.command != "create-user":
                hint = "Check DATABASE_URL" if database.url else "Check DATA_DIR"
                return fail(f"no database at {database.where}. {hint} or start the server once.")
            if database.name == "sqlite":
                database.path.parent.mkdir(parents=True, exist_ok=True)
            print(f"note: creating a new database at {database.where}", file=sys.stderr)
        return admin_command(database, args, fail)
    except database.unavailable as exc:
        return fail(f"can't use the database at {database.where}: {exc}")


