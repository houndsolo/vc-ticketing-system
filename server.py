class Database:
    """Where the data lives: SQLite at DATA_DIR/triage.db (default), or PostgreSQL when
    DATABASE_URL is set. psycopg is imported only then, so SQLite mode needs no packages."""

    def __init__(self, url=None, data_dir="data"):
        self.url = url or None
        if self.url:
            import psycopg
            self.driver = psycopg
            self.name = "postgres"
            options = psycopg.conninfo.conninfo_to_dict(self.url)
            self.where = f"{options.get('host', 'localhost')}:{options.get('port', 5432)}/{options.get('dbname', '')}"
            self.connect_options = {} if "connect_timeout" in options else {"connect_timeout": 5}
            # A lost or unreachable server (e.g. a Patroni failover moving the VIP) fails the
            # request with 503; the next request opens a fresh connection.
            self.unavailable = (psycopg.OperationalError, psycopg.InterfaceError)
        else:
            self.driver = sqlite3
            self.name = "sqlite"
            self.path = Path(data_dir) / "triage.db"
            self.where = str(self.path)
            self.unavailable = ()

    def connect(self, timeout=10):
        """A new connection; every request opens its own and closes it afterwards."""
        if self.url:
            raw = self.driver.connect(self.url, row_factory=pg_row_factory, **self.connect_options)
        else:
            raw = sqlite3.connect(self.path, timeout=timeout)
            raw.row_factory = sqlite3.Row
            raw.execute("PRAGMA foreign_keys=ON")
        return Connection(raw, self)

    def exists(self):
        """Whether there is a dark-triage database to manage (for the admin CLI)."""
        if not self.url:
            return self.path.exists()
        with closing(self.connect()) as db:
            return bool(db.columns("users"))


class Row(tuple):
    """psycopg rows that work like sqlite3.Row: row[0] and row["name"]."""

    def __getitem__(self, key):
        return tuple.__getitem__(self, self.names[key] if isinstance(key, str) else key)

    def keys(self):
        return list(self.names)


def pg_row_factory(cursor):
    names = {column.name: i for i, column in reversed(list(enumerate(cursor.description or ())))}

    def make(values):
        row = Row(values)
        row.names = names
        return row
    return make


class Connection:
    """One database connection. SQL is written once, SQLite style (? placeholders);
    the methods below cover the few places where the dialects differ.
    `with db:` is a transaction: commit on success, rollback on error (the connection stays open)."""

    def __init__(self, raw, database):
        self.raw, self.pg = raw, database.name == "postgres"
        self.dialect = database.name
        self.IntegrityError = database.driver.IntegrityError

    def execute(self, sql, params=()):
        if self.pg:
            sql = sql.replace("%", "%%").replace("?", "%s")
        return self.raw.execute(sql, params)

    def script(self, sql):
        """Run parameterless statements separated by semicolons, inside the current transaction."""
        for statement in sql.split(";"):
            if statement.strip():
                self.raw.execute(statement)

    def insert(self, sql, params):
        """INSERT and return the new row's id."""
        if self.pg:
            return self.execute(sql + " RETURNING id", params).fetchone()[0]
        return self.execute(sql, params).lastrowid

    def lock(self, key):
        """Serialize with other writers until this transaction ends. SQLite: BEGIN IMMEDIATE
        (the database write lock; `key` is ignored). PostgreSQL: an advisory transaction lock on `key`."""
        if self.pg:
            self.execute("SELECT pg_advisory_xact_lock(?)", (key,))
        else:
            if self.raw.in_transaction:
                self.raw.commit()
            self.raw.execute("BEGIN IMMEDIATE")

    def columns(self, table):
        if self.pg:
            rows = self.execute("SELECT column_name FROM information_schema.columns "
                                "WHERE table_schema=current_schema() AND table_name=?", (table,))
            return {row[0] for row in rows}
        return {row[1] for row in self.raw.execute(f"PRAGMA table_info({table})")}

    def commit(self):
        self.raw.commit()

    def close(self):
        self.raw.close()

    def __enter__(self):
        return self

    def __exit__(self, kind, value, traceback):
        if kind is None:
            self.raw.commit()
        else:
            try:
                self.raw.rollback()
            except Exception:  # the connection may be gone; the original error matters
                pass
        return False


def now():
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def valid(value, maximum):
    return isinstance(value, str) and 0 < len(value.strip()) and len(value) <= maximum


def hash_password(password):
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, n=SCRYPT_N, r=SCRYPT_R, p=SCRYPT_P, dklen=32)
    encode = lambda b: base64.b64encode(b).decode()
    return f"scrypt${SCRYPT_N}${SCRYPT_R}${SCRYPT_P}${encode(salt)}${encode(digest)}"


def verify_password(password, stored):
    try:
        scheme, n, r, p, salt, digest = stored.split("$")
        if scheme != "scrypt":
            return False
        expected = base64.b64decode(digest)
        actual = hashlib.scrypt(password.encode(), salt=base64.b64decode(salt), n=int(n), r=int(r), p=int(p),
                                dklen=len(expected), maxmem=64 * 1024 * 1024)
    except (ValueError, TypeError):
        return False
    return hmac.compare_digest(actual, expected)


# Verified against when the username doesn't exist, so timing doesn't reveal accounts.
DUMMY_HASH = hash_password(secrets.token_urlsafe(16))


def password_problem(password, username=""):
    if not isinstance(password, str) or not PASSWORD_MIN <= len(password) <= PASSWORD_MAX:
        return f"Passwords must be {PASSWORD_MIN} to {PASSWORD_MAX} characters."
    if username and password.lower() == username.lower():
        return "The password can't be the same as the username."
    return None


def token_hash(token):
    return hashlib.sha256(token.encode()).hexdigest()


def default_color(name):
    """Deterministic palette color for a username (or a legacy stored name)."""
    digest = hashlib.sha256(("dark-triage:" + str(name or "").strip().lower()).encode()).digest()
    return PALETTE[int.from_bytes(digest[:4], "big") % len(PALETTE)]


def effective_color(custom, name):
    return custom or default_color(name)


def parse_color(value):
    """None (back to the default) or a '#rrggbb' string, normalized to lowercase."""
    if value is None:
        return None
    if not isinstance(value, str) or not COLOR_RE.fullmatch(value):
        raise RequestError(400, "color must be a hex color like #f70997, or null for the default.")
    return value.lower()


